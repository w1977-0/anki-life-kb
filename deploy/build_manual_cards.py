def main():
    """输出两个文件 —— `anki add` 一次只能发一个笔记类型。"""
    base = sys.argv[1] if len(sys.argv) > 1 else "/tmp/manual"
    ex_cards = [c for c in CARDS if "选项" not in c["fields"]]
    qz_cards = [c for c in CARDS if "选项" in c["fields"]]

    p1 = base + "_摘录.json"
    json.dump({"deck": DECK, "notetype": "生活摘录", "cards": ex_cards},
              open(p1, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    p2 = base + "_选择.json"
    json.dump({"deck": DECK, "notetype": "生活选择", "cards": qz_cards},
              open(p2, "w", encoding="utf-8"), ensure_ascii=False, indent=2)

    print(f"生活摘录 {len(ex_cards)} 张 → {p1}")
    print(f"生活选择 {len(qz_cards)} 张 → {p2}")
    print(f"合计 {len(CARDS)} 张，牌组 {DECK}")


if __name__ == "__main__":
    main()
